from rest_framework import serializers
from .models import User


class UserSerializer(serializers.ModelSerializer):
    class Meta:
        model = User
        fields = [
            "id",
            "first_name",
            "last_name",
            "email",
            "phone",
            "role",
            "profile_image",
            "state",
            "district",
            "village",
            "pincode",
            "is_blocked",
            "date_joined",
        ]
        read_only_fields = ["id", "email", "role", "is_blocked", "date_joined"]


